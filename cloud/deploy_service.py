#!/usr/bin/env python3
"""Build the vendored source and deploy request-billed metadata service."""
import json
import subprocess
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parent/'cost-guard'))
from config import PROJECT, REGION, REPO, CONFIG
from deploy import cli

# The TV playlist token travels in the query string; keep these request logs out of storage.
LIVE_LOG_EXCLUSION='lunatv-live-playlist'
LIVE_LOG_FILTER='resource.type="cloud_run_revision" AND resource.labels.service_name="lunatv" AND httpRequest.requestUrl:"/api/live/playlist"'

def exclude_live_playlist_logs():
    sink=cli('logging','sinks','describe','_Default',f'--project={PROJECT}')
    current={e.get('name'):e.get('filter') for e in sink.get('exclusions') or []}
    if current.get(LIVE_LOG_EXCLUSION)==LIVE_LOG_FILTER:return
    flag='--update-exclusion' if LIVE_LOG_EXCLUSION in current else '--add-exclusion'
    cli('logging','sinks','update','_Default',f'--project={PROJECT}',f'{flag}=name={LIVE_LOG_EXCLUSION},filter={LIVE_LOG_FILTER}')

def deploy():
    admin=CONFIG['admin_username']
    import re
    assert re.fullmatch(r'[A-Za-z0-9_-]{1,40}',admin), 'Invalid username'
    # Build ID is generated by Cloud Build; no personal identifier is used in the tag.
    tag='home-tv'
    image=f'{REGION}-docker.pkg.dev/{PROJECT}/home-tv/lunatv:{tag}'
    result=cli('builds','submit',str(REPO/'vendor/LunaTV'),f'--project={PROJECT}',f'--region={REGION}',
        '--config='+str(REPO/'cloud/cloudbuild.yaml'),f'--substitutions=_REGION={REGION},_TAG={tag}',
        f'--service-account=projects/{PROJECT}/serviceAccounts/lunatv-builder@{PROJECT}.iam.gserviceaccount.com',
        f'--gcs-source-staging-dir=gs://{PROJECT}-home-tv-build/source')
    assert result['status']=='SUCCESS', 'Cloud Build did not succeed'
    built=result['results']['images'][0]
    digest_image=image.rsplit(':',1)[0]+'@'+built['digest']
    # Exclude before the revision that serves the playlist endpoint goes live.
    exclude_live_playlist_logs()
    cli('run','deploy','lunatv',f'--project={PROJECT}',f'--region={REGION}',f'--image={digest_image}',
        f'--service-account=lunatv-runtime@{PROJECT}.iam.gserviceaccount.com',
        '--cpu=1','--memory=512Mi','--concurrency=20','--min=0','--max=1','--cpu-throttling',
        '--no-cpu-boost','--timeout=60','--port=3000','--allow-unauthenticated',
        '--set-env-vars=NEXT_PUBLIC_STORAGE_TYPE=upstash,USERNAME='+admin+',NEXT_PUBLIC_SITE_NAME=HomeTV,NEXT_PUBLIC_SEARCH_MAX_PAGE=1,NEXT_PUBLIC_DOUBAN_PROXY_TYPE=direct,NEXT_PUBLIC_DOUBAN_IMAGE_PROXY_TYPE=direct,DISABLE_VIDEO_PROXY=true,DISABLE_BACKGROUND_JOBS=true',
        '--set-secrets=PASSWORD=lunatv-admin-password:latest,UPSTASH_URL=lunatv-upstash-url:latest,UPSTASH_TOKEN=lunatv-upstash-token:latest,LIVE_PLAYLIST_TOKEN=lunatv-live-token:latest')
    service=cli('run','services','describe','lunatv',f'--project={PROJECT}',f'--region={REGION}')
    saved={'service_url':service['status']['url'],'image':digest_image,'build_id':result['id']}
    (REPO/'.local/service.json').write_text(json.dumps(saved,indent=2)+'\n')
    print('Service deployed. URL and image receipt saved in .local/service.json')
if __name__=='__main__':deploy()
